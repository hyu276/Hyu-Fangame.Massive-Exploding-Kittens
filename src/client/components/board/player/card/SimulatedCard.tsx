interface SimulatedCardProps {
  card: { name: string; index?: number } | string | null;
  className?: string;
  style?: React.CSSProperties;
}

export const SimulatedCard: React.FC<SimulatedCardProps> = ({ card, className = '', style }) => {
  if (!card) return null;

  const cardName = typeof card === 'string' ? card : card.name;
  const info = getCardInfo(card);
  const icon = CARD_ICONS[cardName] || '🃏';
  const borderCol = info.badgeColor || '#38bdf8';

  return (
    <div
      className={`simulated-card-inner ${className}`}
      style={{
        ...style,
        ['--sim-border' as any]: borderCol,
        borderColor: borderCol,
      }}
    >
      <div className="simulated-card-header">
        <span className="simulated-card-title">{info.vietnameseName}</span>
        <span className="simulated-card-subtitle">{info.englishName}</span>
      </div>

      <div className="simulated-card-icon">{icon}</div>

      <div className="simulated-card-footer">
        <div className="simulated-card-effect">{info.shortEffect}</div>
      </div>
    </div>
  );
};

export default SimulatedCard;
