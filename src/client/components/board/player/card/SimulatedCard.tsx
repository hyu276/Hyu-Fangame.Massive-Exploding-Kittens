/**
 * Kiểm tra xem thẻ bài có cần render bằng giao diện mô phỏng (SimulatedCard) hay không.
 * Nguyên tắc vàng: BẤT KỲ thẻ nào không có hình ảnh trên đĩa (REAL_IMAGE_CARD_NAMES)
 * đều PHẢI được mô phỏng để không bao giờ bị ô trống chữ nhật rỗng hoặc 404 cho người chơi.
 */
export function isCardSimulated(cardName: string | null | undefined): boolean {
  if (!cardName) return false;
  return !REAL_IMAGE_CARD_NAMES.has(cardName) && !configuredArtworkTypes.has(cardName);
}

