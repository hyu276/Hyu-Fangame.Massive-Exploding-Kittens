/**
 * Lấy thông tin chú thích hiệu ứng Tiếng Việt của thẻ bài
 */
export function getCardInfo(card: { name: string; index?: number } | string | null | undefined): ICardInfo {
  if (!card) {
    return {
      name: 'unknown',
      vietnameseName: 'Thẻ Bài',
      englishName: 'Card',
      category: 'Khác',
      shortEffect: 'Mặt sau của thẻ bài.',
      description: 'Lá bài đang úp mặt.',
      instructions: '',
      badgeColor: '#64748b',
    };
  }

  const cardName = typeof card === 'string' ? card : card.name;
  const cardIndex = typeof card === 'object' && card.index !== undefined ? card.index : undefined;

  const baseInfo = CARD_INFO_MAP[cardName];
  if (!baseInfo) {
    return {
      name: cardName,
      vietnameseName: cardName,
      englishName: cardName,
      category: 'Tùy Chỉnh',
      shortEffect: 'Thẻ bài mới.',
      description: 'Chưa có mô tả chi tiết cho thẻ bài này.',
      instructions: '',
      badgeColor: '#64748b',
    };
  }

  // Nếu là cat_card và có index, bổ sung tên chi tiết loài mèo
  if (cardName === NAME_CAT_CARD && cardIndex !== undefined && CAT_CARD_VARIANTS[cardIndex]) {
    const variant = CAT_CARD_VARIANTS[cardIndex];
    return {
      ...baseInfo,
      vietnameseName: `${variant.name} (Đánh Cặp)`,
      englishName: `${variant.englishName} (Cat Pair)`,
      description: `[${variant.name}]: ${baseInfo.description}`,
    };
  }

  return baseInfo;
}
